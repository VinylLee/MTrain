"""Prepare version-blind paired human reviews and assess supplied human answers."""
from __future__ import annotations
import argparse
from collections import defaultdict
import json
from pathlib import Path
import random
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from nli_v3_4 import core
from nli_v3_4.data import DATASETS, canonical_source, digest, is_source, load_dataset, sha256, write_json, write_jsonl


def package(old_root, new_root, output, per_mr=20, seed=42, stage="development"):
    if per_mr not in {20, 40}:
        raise ValueError("review size must be 20 or 40 pairs per MR")
    output = Path(output)
    if output.exists():
        raise FileExistsError(output)
    groups = defaultdict(list)
    provenance = {}
    for dataset in ("train", *DATASETS):
        paths = [Path(old_root)/f"{dataset}.jsonl", Path(new_root)/f"{dataset}.jsonl"]
        sides = []
        for path in paths:
            rows, sources = load_dataset(path)
            source_by_id = {r["pair_id"]: r for r in sources}
            if path.with_suffix(".run.json").exists():
                meta = json.loads(path.with_suffix(".run.json").read_text())
            elif stage == "production" and path == paths[0]:
                meta = {"stage": "historical_baseline", "source_sha256": digest([canonical_source(r) for r in sources])}
            else:
                raise ValueError("missing generation provenance")
            if meta["stage"] not in ({"development"} if stage == "development" else {"production", "historical_baseline"}):
                raise ValueError("review stage differs from generation stage")
            follows = {}
            occurrences = defaultdict(int)
            for r in rows:
                if not is_source(r):
                    base = (r["pair_id"], r["mr_id"])
                    ordinal = occurrences[base]
                    occurrences[base] += 1
                    follows[(*base, ordinal)] = r
            sides.append((follows, source_by_id, meta))
        if sides[0][2]["source_sha256"] != sides[1][2]["source_sha256"]:
            raise ValueError("old/new source cohorts differ")
        if sides[1][2]["contract_sha256"] != core.fingerprint():
            raise ValueError("new output was generated by another contract")
        provenance[dataset] = {"v3_3_path": str(paths[0].resolve()), "v3_4_path": str(paths[1].resolve()),
                              "v3_3_sha256": sha256(paths[0]), "v3_4_sha256": sha256(paths[1])}
        # Sample new outputs without conditioning on old generation success. Otherwise
        # new-only errors could disappear from the quality audit.
        for key, new in sides[1][0].items():
            pair_id, operation, ordinal = key
            groups[operation].append((dataset, sides[0][1][pair_id], sides[0][0].get(key), new, ordinal))
    rng = random.Random(seed)
    label_rows, operation_rows, private, requested = [], [], [], []
    for operation in core.OPERATION_SPECS:
        available = sorted(groups[operation], key=lambda x: (x[0], x[1]["pair_id"]))
        buckets = defaultdict(list)
        for item in available:
            buckets[item[0]].append(item)
        for bucket in buckets.values():
            rng.shuffle(bucket)
        selected = []
        while len(selected) < per_mr and any(buckets.values()):
            for dataset in ("train", *DATASETS):
                if buckets[dataset] and len(selected) < per_mr:
                    selected.append(buckets[dataset].pop())
        for dataset, source, old, new, ordinal in selected:
            pair_key = digest([dataset, source["pair_id"], operation, ordinal])
            requested.append(pair_key)
            for version, row in (("v3.3", old), ("v3.4", new)):
                if row is None:
                    continue
                review_id = digest([pair_key, version, seed])[:20]
                label_rows.append({"review_id": review_id, "premise": row["premise"], "hypothesis": row["hypothesis"]})
                operation_rows.append({"review_id": review_id, "source_hypothesis": source["hypothesis"],
                    "hypothesis": row["hypothesis"], "operation": operation,
                    "operation_definition": core.OPERATION_SPECS[operation]["instruction"],
                    "component_mrs": row.get("component_mrs")})
                private.append({"review_id": review_id, "pair_key": pair_key, "dataset": dataset,
                    "pair_id": source["pair_id"], "version": version, "operation": operation,
                    "expected_label": row["label"], "is_inv": row["mr_type"] == "inv"})
                private[-1]["paired"] = old is not None
    rng.shuffle(label_rows); rng.shuffle(operation_rows)
    write_jsonl(output/"label_grammar_blind.jsonl", label_rows)
    write_jsonl(output/"operation_blind.jsonl", operation_rows)
    write_jsonl(output/"private_key.jsonl", private)
    write_json(output/"answers.template.json", {"reviewer": "", "human_attestation": False,
        "answers": [{"review_id": r["review_id"], "label": None, "grammatical": None,
                     "operation_valid": None, "source_equivalent": None} for r in label_rows]})
    write_json(output/"manifest.json", {"stage": stage, "contract_sha256": core.fingerprint(),
        "datasets": provenance, "pairs": len(requested), "per_mr_target": per_mr,
        "available_new_review_units_per_mr": {op: len(groups[op]) for op in core.OPERATION_SPECS},
        "new_only_units": sum(k["version"]=="v3.4" and not k["paired"] for k in private),
        "private_key_sha256": sha256(output/"private_key.jsonl"),
        "label_grammar_sha256": sha256(output/"label_grammar_blind.jsonl"),
        "operation_sha256": sha256(output/"operation_blind.jsonl")})
    (output/"README_zh.md").write_text("先完成 label_grammar_blind.jsonl 的标签和语言判断，再阅读 operation_blind.jsonl 判断操作。\n"
        "不要读取 private_key.jsonl，也不要查看版本或模型分数。将结果填入 answers.template.json 的副本；\n"
        "label 为 0=E、1=N、2=C，其余为布尔值；非 INV 的 source_equivalent 可留 null。\n"
        "reviewer 填真实审核人标识，完成后 human_attestation=true。自动模型意见不能作为人工回答。\n")


def assess(review_root, answers_path, output):
    import numpy as np
    root = Path(review_root)
    manifest = json.loads((root/"manifest.json").read_text())
    if manifest["private_key_sha256"] != sha256(root/"private_key.jsonl"):
        raise ValueError("private review key changed")
    for dataset in manifest["datasets"].values():
        for version in ("v3_3", "v3_4"):
            if sha256(dataset[f"{version}_path"]) != dataset[f"{version}_sha256"]:
                raise ValueError("reviewed data changed")
    supplied = json.loads(Path(answers_path).read_text())
    if supplied.get("human_attestation") is not True or not str(supplied.get("reviewer", "")).strip():
        raise ValueError("requires completed review by a named human")
    keys = [json.loads(line) for line in (root/"private_key.jsonl").read_text().splitlines() if line]
    answers = {r["review_id"]: r for r in supplied["answers"]}
    if len(answers) != len(supplied["answers"]) or set(answers) != {r["review_id"] for r in keys}:
        raise ValueError("missing/duplicate/unknown review answers")
    values = defaultdict(lambda: defaultdict(dict))
    per_version = defaultdict(lambda: defaultdict(list))
    for key in keys:
        answer = answers[key["review_id"]]
        if type(answer.get("label")) is not int or answer["label"] not in (0,1,2):
            raise ValueError("human label must be an NLI integer")
        if any(type(answer.get(k)) is not bool for k in ("grammatical", "operation_valid")):
            raise ValueError("incomplete human review")
        if key["is_inv"] and type(answer.get("source_equivalent")) is not bool:
            raise ValueError("INV requires an explicit equivalence judgment")
        criteria = {"label": answer["label"] == key["expected_label"],
                    "grammar": answer["grammatical"], "operation": answer["operation_valid"]}
        if key["is_inv"]:
            criteria["inv_equivalence"] = answer["source_equivalent"]
        # Bootstrap the source group; multiple MRs from one source remain clustered.
        group = (key["dataset"], key["pair_id"])
        for criterion, result in criteria.items():
            if key.get("paired", True):
                values[criterion][group].setdefault(key["version"], []).append(int(result))
            per_version[criterion][key["version"]].append(int(result))
    summary = {}
    for criterion, groups in values.items():
        counts=[]
        for versions in groups.values():
            old,new=versions["v3.3"],versions["v3.4"]
            counts.append([sum(old),len(old),sum(new),len(new)])
        counts=np.asarray(counts);rng=np.random.default_rng(42);diffs=[]
        for _ in range(1500):
            c=counts[rng.integers(0,len(counts),len(counts))].sum(axis=0)
            diffs.append(c[2]/c[3]-c[0]/c[1])
        old=float(np.mean(per_version[criterion]["v3.3"]));new=float(np.mean(per_version[criterion]["v3.4"]))
        paired_old=sum(c[0] for c in counts)/sum(c[1] for c in counts)
        paired_new=sum(c[2] for c in counts)/sum(c[3] for c in counts)
        ci=np.quantile(diffs,[.025,.975]).tolist()
        summary[criterion]={"v3_3":old,"v3_4":new,"difference_ci95":ci,
            "paired_v3_3":float(paired_old),"paired_v3_4":float(paired_new),
            "passes":new>=.95 and new>=old and paired_new>=paired_old and ci[0]>=-.02}
    result={**manifest,"human_review_complete":True,"reviewer":supplied["reviewer"],
            "answers_sha256":sha256(answers_path),"criteria":summary,
            "quality_passed":set(summary)=={"label","grammar","operation","inv_equivalence"}
                and all(v["passes"] for v in summary.values())}
    if Path(output).exists():
        raise FileExistsError(output)
    write_json(output,result)


def main():
    p=argparse.ArgumentParser(description=__doc__);sub=p.add_subparsers(dest="command",required=True)
    q=sub.add_parser("package")
    q.add_argument("--old-root",type=Path,required=True);q.add_argument("--new-root",type=Path,required=True)
    q.add_argument("--output",type=Path,required=True);q.add_argument("--per-mr",type=int,default=20)
    q.add_argument("--stage",choices=("development","production"),default="development")
    q=sub.add_parser("assess")
    q.add_argument("--review-root",type=Path,required=True);q.add_argument("--answers",type=Path,required=True)
    q.add_argument("--output",type=Path,required=True)
    a=p.parse_args()
    if a.command=="package":package(a.old_root,a.new_root,a.output,a.per_mr,stage=a.stage)
    else:assess(a.review_root,a.answers,a.output)


if __name__=="__main__":main()
